"""T18 -- the slide deck's numbers, written from the measured JSONs only (out/t17_<case>.json): one LaTeX file per case
(doc/num_<case>.tex) with the case's table and its macros. Thrust differences in ppm (parts per million of the
optimum's thrust: 1 ppm = 1 N per MN); wall differences in thousandths of the reference length (mm per m).
usage: t18_numbers.py [case ...]   (default: every out/t17_*.json)
"""
