DIG = dict(zip("0123456789", ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]))


def mname(k):
    """a LaTeX-safe macro fragment from a run key (letters kept, digits spelled out)"""
    return "".join(DIG.get(ch, ch) for ch in k.title() if ch.isalnum())


def lim_err(seq, rich):
    """the Richardson limit of a 3-grid sequence and an honest error bar: at least the last change between grids
    (an extrapolation from a sequence not yet in its asymptotic range under-states its own error)"""
    return rich[0], max(rich[1], abs(seq[-1] - seq[-2]))


def ppm(v, signed=True):
    if v is None:
        return "--"
    x = 1e6 * v
    if abs(x) >= 100:
        return ("%+.0f" if signed else "%.0f") % x
    if abs(x) >= 10:
        return ("%+.1f" if signed else "%.1f") % x
    return ("%+.2f" if signed else "%.2f") % x


def tmin(sec):
    return "%.0f\\,s" % sec if sec < 120 else "%.0f\\,min" % (sec / 60.0)


def one(case):
    d = json.load(open(os.path.join(rv.OUT, "t17_%s.json" % case)))
    m = MAC[case]
    lab = LAB[case]
    same = all(max(abs(a - b) for a, b in zip(r_["gap"], r_["minus_fit"])) < 1e-12
               for r_ in d["runs"].values())                         # the reference IS the closest curve
    if same:
        lines = ["%% generated by tests/t18_numbers.py from out/t17_%s.json -- do not edit" % case,
                 "\\begin{tabular}{@{}lrrrrr@{}}\\toprule",
                 " & \\multicolumn{3}{c}{vs the closest curve to GENO's wall} & & \\\\",
                 "start & optimiser's grid & finest & limit & steps & time\\\\\\midrule"]
        for k, r in d["runs"].items():
            if k == "fit":
                continue
            rep = d.get("report", {}).get(k, {}) or {}
            wl = r.get("walk_level", 0)
            mlim, merr = lim_err(r["minus_fit"], r["minus_fit_lim"])
            sec = rep.get("seconds")
            lines.append("%s & %s & %s & %s$\\pm$%s & %s & %s\\\\" % (
                lab.get(k, k), ppm(r["minus_fit"][wl]), ppm(r["minus_fit"][-1]), ppm(mlim), ppm(merr, False),
                rep.get("segments", "--"), tmin(sec) if sec else "--"))
        lines += ["\\bottomrule", "\\end{tabular}"]
    lines = lines if same else ["%% generated by tests/t18_numbers.py from out/t17_%s.json -- do not edit" % case,
             "\\begin{tabular}{@{}lrrrrrr@{}}\\toprule",
             " & \\multicolumn{2}{c}{vs the optimum} & \\multicolumn{2}{c}{vs its closest curve} & & \\\\",
             "start & optimiser's grid & finest & optimiser's grid & limit & steps & time\\\\\\midrule"]
    for k, r in (d["runs"].items() if not same else []):
        if k == "fit":
            continue
        rep = d.get("report", {}).get(k, {}) or {}
        g = r["gap"]
        wl = r.get("walk_level", 0)
        lim, err, _ = r["gap_lim"]
        trials = rep.get("segments", "--")
        sec = rep.get("seconds")
        mf = r["minus_fit"]
        mlim, merr = lim_err(r["minus_fit"], r["minus_fit_lim"])
        lines.append("%s & %s & %s & %s & %s$\\pm$%s & %s & %s\\\\" % (lab.get(k, k), ppm(g[wl]), ppm(g[-1]), ppm(mf[wl]),
                                                                  ppm(mlim), ppm(merr, False), trials,
                                                                  tmin(sec) if sec else "--"))
    if not same:
        r = d["runs"]["fit"]
        lines.append("\\midrule %s & %s & %s & 0 & 0 & & \\\\" % (lab["fit"], ppm(r["gap"][0]), ppm(r["gap"][-1])))
        lines += ["\\bottomrule", "\\end{tabular}"]
    open(os.path.join(DOC, "num_%s_table.tex" % case), "w").write("\n".join(lines) + "\n")
    mac = ["%% generated by tests/t18_numbers.py from out/t17_%s.json -- do not edit" % case]
    if "pair" in d:
        p = d["pair"]
        mac.append("\\newcommand{\\%sPairJ}{%s}" % (m, ppm(abs(p["dJ"][-1]), False)))
        mac.append("\\newcommand{\\%sPairJwalk}{%s}" % (m, ppm(abs(p["dJ"][0]), False)))
        mac.append("\\newcommand{\\%sPairWall}{%.2f}" % (m, 1e3 * p["dwall"]))
    if "pair81" in d:
        p = d["pair81"]
        mac.append("\\newcommand{\\%sPairJFine}{%s}" % (m, ppm(abs(p["dJ"][-1]), False)))
        mac.append("\\newcommand{\\%sPairWallFine}{%.2f}" % (m, 1e3 * p["dwall"]))
    mac.append("\\newcommand{\\%sYard}{%s}" % (m, ppm(d["yardstick"], False)))
    for k, r in d["runs"].items():
        kk = mname(k)
        wl = r.get("walk_level", 0)                 # the grid this run was optimised on
        mac.append("\\newcommand{\\%s%sWalk}{%s}" % (m, kk, ppm(r["gap"][wl])))
        mac.append("\\newcommand{\\%s%sFine}{%s}" % (m, kk, ppm(r["gap"][-1])))
        mac.append("\\newcommand{\\%s%sLim}{%s}" % (m, kk, ppm(r["gap_lim"][0])))
        mac.append("\\newcommand{\\%s%sMinusFitWalk}{%s}" % (m, kk, ppm(r["minus_fit"][wl])))
        mac.append("\\newcommand{\\%s%sMinusFitLim}{%s}" % (m, kk, ppm(r["minus_fit_lim"][0])))
        rep = d.get("report", {}).get(k, {}) or {}
        if rep:
            mac.append("\\newcommand{\\%s%sTrials}{%s}" % (m, kk, rep.get("segments", "--")))
            mac.append("\\newcommand{\\%s%sRecords}{%s}" % (m, kk, rep.get("records", "--")))
            mac.append("\\newcommand{\\%s%sTime}{%s}" % (m, kk, tmin(rep["seconds"]) if rep.get("seconds") else "--"))
            mac.append("\\newcommand{\\%s%sStop}{%s}" % (m, kk, str(rep.get("stop", "--")).lower()))
            gp = rep.get("gain_pred_rel")
            mac.append("\\newcommand{\\%s%sPred}{%s}" % (m, kk, ("%.1g" % (1e6 * gp)) if gp is not None else "--"))
    if case == "hth":
        mac.append("\\newcommand{\\HthDoneFlag}{}")      # the slide switches from 'running' to the final text
        # Humphreys' thrust of Rao's contour from a characteristic of its own field, 34,375 lbf, times our ratio
        g = [d["runs"][k]["gap"][-1] for k in ("bump", "half") if k in d["runs"]]
        mac.append("\\newcommand{\\HthLbf}{%s\\,lbf (%s / %s\\,lbf vs Rao)}" % (
            "{:,.0f}".format(34375.0 * (1.0 + g[0])).replace(",", "\\,"),
            "%+.2f" % (34375.0 * g[0]), "%+.2f" % (34375.0 * g[-1])))
    if "geno_over_bound_lim" in d:
        mac.append("\\newcommand{\\%sGenoBound}{%s}" % (m, ppm(d["geno_over_bound_lim"][0])))
    if "thB" in d:
        for k, v in d["thB"].items():
            kk = mname(k)
            mac.append("\\newcommand{\\%sThB%s}{%.2f}" % (m, kk, v))
    open(os.path.join(DOC, "num_%s.tex" % case), "w").write("\n".join(mac) + "\n")
    print("wrote doc/num_%s.tex, doc/num_%s_table.tex" % (case, case))


cases = sys.argv[1:] or [os.path.basename(f)[4:-5] for f in sorted(glob.glob(os.path.join(rv.OUT, "t17_*.json")))]
for c in cases:
    one(c)


